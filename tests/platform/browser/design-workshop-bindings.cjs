"use strict";

// Exercise result/configuration binding without submitting physical calculations.
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const source=fs.readFileSync(path.resolve(__dirname,"../../../src/camera_platform/static/design-workshop.js"),"utf8");
const fields=new Map();
const context={document:{getElementById:id=>fields.get(id)},console};
vm.createContext(context);
const instrumented=source.replace("  init();\n})();","  globalThis.bindingTest={state,viewFrom,configuration,imagePath,fileURL,equivalent,crossing,readAxes};\n})();");
assert.notEqual(instrumented,source,"Test must replace only the application entry point");
vm.runInContext(instrumented,context);
const ui=context.bindingTest;
const spec={name:"baseline",lens:{controls:{sensor_shift_um:0}},pixel:{cfa_thickness_scale:1},isp:{sharpen:.3},scene:"composite"};
const clone=x=>JSON.parse(JSON.stringify(x));
const good={id:"run-123",status:"succeeded",specification:spec,result:{summary:{configuration:spec,images:{composite:{display:"composite/display.png",raw:"composite/raw-00.npy",raw_preview:"composite/raw.png",reference:"composite/source-reference.png"},color:{display:"color/display.png"}},optics:{images:{psf:"psf.png"}}}}};
const single=ui.viewFrom(good);
assert.equal(ui.configuration(single),spec);
assert.equal(ui.imagePath(single,"isp"),"composite/display.png");
assert.equal(ui.imagePath(single,"raw"),"composite/raw.png");
assert.equal(ui.imagePath(single,"scene"),"composite/source-reference.png");
assert.equal(ui.imagePath(single,"psf"),"optics/psf.png");
assert.equal(ui.imagePath(single,"optical"),null,"Do not invent a missing optical image");
const noPreview=clone(good);delete noPreview.result.summary.images.composite.raw_preview;
assert.equal(ui.imagePath(ui.viewFrom(noPreview),"raw"),null,"NPY must never become an img source");
ui.state.preview="color";
assert.equal(ui.imagePath(single,"isp"),"color/display.png");
ui.state.preview="primary";
const candidateSpec={...clone(spec),name:"candidate",pixel:{cfa_thickness_scale:1.1}};
const sweep={id:"run-456",status:"succeeded",result:{summary:{candidates:[{id:"candidate-00",status:"succeeded",configuration:candidateSpec,files_base:"/api/v1/design-workshop/runs/run-456/files/candidate-00/",images:good.result.summary.images},{id:"candidate-01",status:"failed",configuration:spec,error:"unsupported"}]}}};
const selected=ui.viewFrom(sweep,"candidate-00");
assert.equal(ui.configuration(selected),candidateSpec,"Selecting a candidate must bind its own specification");
assert.equal(ui.fileURL(selected,ui.imagePath(selected,"isp")),"/api/v1/design-workshop/runs/run-456/files/candidate-00/composite/display.png");
assert.throws(()=>ui.viewFrom(sweep,"candidate-01"),/완료된 계산/);
assert.throws(()=>ui.viewFrom(sweep,"unknown"),/찾을 수/);
assert.throws(()=>ui.viewFrom({...good,status:"running"}),/완료된 실행/);
assert.throws(()=>ui.viewFrom(good,"candidate-00"),/개별 탐색 후보/);
const ispOnly=clone(spec);ispOnly.name="detail";ispOnly.isp.sharpen=1.2;
assert.equal(ui.equivalent(spec,ispOnly,true),true,"Same-RAW replay permits name/ISP only");
assert.equal(ui.equivalent(spec,ispOnly,false),false);
assert.equal(ui.equivalent(spec,candidateSpec,true),false,"Pixel changes require acquisition");
assert.equal(ui.crossing([0,.25,.5],[1,.5,.2]),.25);
assert.equal(ui.crossing([0,.25,.5],[1,.9,.7]),null,"No 50% crossing must stay null");
for(const [id,value] of Object.entries({"sweep-mode":"2d3","sweep-x":"lens.controls.sensor_shift_um","sweep-x-values":"-10, 0, 10","sweep-y":"pixel.cfa_thickness_scale","sweep-y-values":"0.9, 1, 1.1"}))fields.set(id,{value});
assert.equal(ui.readAxes().length,2);
fields.get("sweep-y").value="lens.controls.sensor_shift_um";
assert.throws(()=>ui.readAxes(),/서로 다른/);
fields.get("sweep-y").value="pixel.cfa_thickness_scale";
fields.get("sweep-y-values").value="1, 1, 1.1";
assert.throws(()=>ui.readAxes(),/중복 없이/);
console.log("Design Workshop bindings: 23 result, source-preservation and sweep checks passed");
