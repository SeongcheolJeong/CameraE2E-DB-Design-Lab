def capture_effects(payload):
    program = validate_capture_program(payload)
    effects = [
        *TEMPORAL_EFFECTS,
        "electrical_readout",
        "retained_photodiode_charge",
        "partial_charge_transfer",
        "continuous_interframe_dark_current",
    ]
    if program["electrical_model"]["schema"].endswith("_v2"):
        effects.append("nonlinear_charge_voltage_response")
    if _paired(program["electrical_model"]):
        effects.append("shared_delivered_charge_two_conversion_paths")
    if program["waveform"] is not None:
        effects.append("periodic_light_modulation")
    if program["schema"] in TRAPPED_SCHEMAS:
        effects.append("authored_bounded_photodiode_trap_capture_release")
    if program["schema"] in GAIN_MERGE_SCHEMAS:
        effects.append("raw_only_shared_delivered_charge_gain_path_merge")
    if program["schema"] == PHOTO_HDR_PROGRAM_SCHEMA:
        effects.append("causal_raw_only_retained_photo_rate_hdr_selection")
    return effects


def event_schedule(control, program, geometry, shape):
    """Freeze actual row times before job identity/cache hashing, with no external state."""
    full, origin = geometry["full_sensor_shape"], geometry["crop_origin"]
    if (len(full) != 2 or len(origin) != 2 or len(shape) != 2
            or any(type(value) is not int for value in (*full, *origin, *shape))
            or any(start < 0 or side < 2 or side % 2 or start + side > maximum
                   for start, side, maximum in zip(origin, shape, full, strict=True))):
        raise ValueError("Retained receiver ROI must fit the full native sensor")
    cropped = list(origin) != [0, 0] or list(full) != list(shape)
    frames = control["frames"]
    if [p["frame_id"] for p in program["pd_clear_before_exposure"]] != [
        f["frame_id"] for f in frames
    ]:
        raise ValueError("PD clear policies must match every control frame ID exactly in order")
    rows, previous = [], None
    for frame, policy in zip(frames, program["pd_clear_before_exposure"], strict=True):
        window = row_windows(frame, control["mode"], geometry, shape)
        starts, ends = window["row_start_ns"], window["row_end_ns"]
        gaps = (
            [0] * len(starts)
            if previous is None
            else [a - b for a, b in zip(starts, previous, strict=True)]
        )
        if min(gaps) < 0:
            raise ValueError("Retained same-row exposure windows cannot overlap")
        rows.append(
            {
                "frame_id": frame["frame_id"],
                "row_open_ns": list(starts),
                "row_transfer_ns": list(ends),
                "row_clear_ns": list(starts) if policy["clear"] else None,
                "row_gap_ns": gaps,
                "clear_before_exposure": policy["clear"],
            }
        )
        previous = ends
    result = {
        "schema": (
            ("camera_retained_row_events_v4" if program["schema"] in TRAPPED_SCHEMAS
             else "camera_retained_row_events_v3") if cropped else
            ("camera_retained_row_events_v2" if program["schema"] in TRAPPED_SCHEMAS
             else "camera_retained_row_events_v1")
        ),
        "clock": deepcopy(control["clock"]),
        "event_contract": deepcopy(program["event_contract"]),
        "full_sensor_shape": list(full),
        **({"capture_crop": {"crop_origin": list(origin), "shape": list(shape)}}
           if cropped else {}),
        "initial_row_time_ns": rows[0]["row_open_ns"],
        "frames": rows,
    }
    return {**result, "schedule_sha256": digest(result)}


def _parse(request):
    if not isinstance(request, Mapping) or "capture_program" not in request:
        raise ValueError("Retained runtime requires an explicit capture program")
    program = validate_capture_program(request["capture_program"])
    unmodulated_input = request.get("unmodulated_scene_sequence")
    source_ri = "field_radiometry_mode" in request
    if source_ri and (
        type(request["field_radiometry_mode"]) is not str
        or request["field_radiometry_mode"] != SOURCE_RI_MODE
        or program["schema"] != TRAPPED_GAIN_MERGE_PROGRAM_SCHEMA
        or not _paired(program["electrical_model"])
        or program["waveform"] is None
        or program["waveform"]["kind"] != "pwm"
        or unmodulated_input is None
    ):
        raise ValueError(
            "Retained source-position RI requires a trapped HCG/LCG program, "
            "explicit PWM and two independent scene sequences"
        )
    if unmodulated_input is not None and (
        program["schema"] == PHOTO_HDR_PROGRAM_SCHEMA
        or program["waveform"] is None
    ):
        raise ValueError(
            "Two illumination components require retained RAW v1/v2/v3/v4 "
            "and an explicit PWM/light waveform; photo HDR remains unsupported"
        )
    base_request = {
        k: v for k, v in request.items()
        if k not in {"capture_program", "retained_charge_events", "unmodulated_scene_sequence"}
    }
    parsed = _parse_temporal(base_request, allow_source_ri=source_ri)
    parsed["program"] = program
    if unmodulated_input is not None:
        unmodulated = _parse_temporal(
            {**base_request, "scene_sequence": unmodulated_input},
            allow_source_ri=source_ri,
        )
        for key in ("geometry", "size", "source_support", "capture_support"):
            if unmodulated["base"].get(key) != parsed["base"].get(key):
                raise ValueError("Illumination components require identical native geometry")
        for key in ("wave", "pitch"):
            if not np.array_equal(unmodulated["base"][key], parsed["base"][key]):
                raise ValueError("Illumination components require identical wavelength/pitch")
        if (unmodulated["timeline"]["clock"] != parsed["timeline"]["clock"]
                or unmodulated["control"] != parsed["control"]):
            raise ValueError("Illumination components require one exact capture clock/control")
        unmodulated["program"] = program
        parsed["unmodulated"] = unmodulated
    base, control = parsed["base"], parsed["control"]
    schedule = event_schedule(control, program, base["geometry"], base["size"])
    photo_hdr = program["schema"] == PHOTO_HDR_PROGRAM_SCHEMA
    if photo_hdr:
        if base["geometry"]["crop_origin"] != [0, 0] or base["geometry"][
            "full_sensor_shape"] != list(base["size"]):
            raise ValueError("Retained photo HDR inverse requires a full-native sensor")
        if len(control["frames"]) < 2 or len(parsed["unique"]) != 1:
            raise ValueError("Stateful photo HDR requires two frames and one exact static scene")
        if len({f["applied"]["exposure_ns"] for f in control["frames"]}) < 2:
            raise ValueError("Stateful photo HDR requires two distinct actual exposures")
    if "retained_charge_events" in request and digest(request["retained_charge_events"]) != digest(
        schedule
    ):
        raise ValueError("Frozen retained row events differ from actual control row times")
    parsed["events"] = schedule
    model = program["electrical_model"]
    module, paired = _readout_module(model), _paired(model)
    if "charge_collection" in base and model["fixed_pattern"]["prnu_sigma"] != 0:
        raise ValueError("Charge collection requires PRNU=0 at source generation")
    formats = _raw_formats(model)
    if any(
        f["bit_depth"] != base["readout"]["bit_depth"]
        or (not paired and f["black_level_dn"] != base["readout"]["black_level_dn"])
        for f in formats
    ):
        raise ValueError("Delivered RAW ADC differs from the fixed native sensor format")
    temperature = (
        model["reference_temperature_c"] if base["temperature"] is None else base["temperature"]
    )
    for frame in control["frames"]:
        applied = frame["applied"]
        if paired:
            if applied["gain"] != 1:
                raise ValueError("Shared delivered-charge readout requires acquisition gain one")
            module.validate_capture_conditions(model, applied["exposure_ns"] / 1e9, temperature)
        else:
            module.validate_capture_conditions(
                model,
                applied["exposure_ns"] / 1e9,
                analog_gain=applied["gain"],
                temperature_c=temperature,
            )
    waveform = program["waveform"]
    if waveform is not None and waveform["clock_id"] != control["clock"]["clock_id"]:
        raise ValueError("Waveform clock must match retained scene/control clock")
    resources = _hdr_resources(parsed)
    if "unmodulated" in parsed:
        unmodulated = parsed["unmodulated"]
        second = _hdr_resources(unmodulated)
        if (parsed["unique_spectral_samples"] + unmodulated["unique_spectral_samples"]
                > hdr_runtime.MAX_UNIQUE_SPECTRAL_SAMPLES):
            raise ValueError("Combined illumination components exceed spectral sample budget")
        if (resources.get("field_psf_fft_work_units", 0)
                + second.get("field_psf_fft_work_units", 0)
                > hdr_runtime.MAX_FIELD_FFT_WORK
                or resources.get("native_direction_weighted_samples", 0)
                + second.get("native_direction_weighted_samples", 0)
                > hdr_runtime.MAX_NATIVE_DIRECTION_WORK
                or parsed["resources"].get("collection_routing_samples", 0)
                + unmodulated["resources"].get("collection_routing_samples", 0)
                > 512_000_000):
            raise ValueError("Combined illumination components exceed optical work budget")
        resources.update(
            working_array_bytes_estimate=(resources["working_array_bytes_estimate"]
                                          + second["working_array_bytes_estimate"]),
            unique_scenes=resources["unique_scenes"] + second["unique_scenes"],
            unique_spectral_samples=(parsed["unique_spectral_samples"]
                                     + unmodulated["unique_spectral_samples"]),
            collection_routing_samples=(
                parsed["resources"].get("collection_routing_samples", 0)
                + unmodulated["resources"].get("collection_routing_samples", 0)
            ),
            illumination_components={
                "schema": ILLUMINATION_COMPONENT_SCHEMA,
                "modulated_unique_scenes": len(parsed["unique"]),
                "unmodulated_unique_scenes": len(unmodulated["unique"]),
            },
        )
        if resources["working_array_bytes_estimate"] > 1024**3:
            raise ValueError("Combined illumination components exceed working-array budget")
    source_ri_map_bytes = {}
    if source_ri:
        source_ri_map_bytes = {
            "modulated": parsed["resources"]["source_position_ri_map_bytes"],
            "unmodulated": parsed["unmodulated"]["resources"][
                "source_position_ri_map_bytes"],
        }
        weighted_work = sum(component["base"]["source_ri_extra_bytes"] for component in
                            (parsed, parsed["unmodulated"]))
        resources["working_array_bytes_estimate"] += (
            weighted_work + sum(source_ri_map_bytes.values()))
        resources["source_position_ri"] = {
            "mode": SOURCE_RI_MODE,
            "component_map_bytes": source_ri_map_bytes,
            "temporary_weighting_bytes_estimate": weighted_work,
            "source_grid_contract": "separate_native_cell_or_subcell_grid_per_component",
        }
    pixels = int(np.prod(base["size"]))
    count = len(control["frames"])
    trapped = program["schema"] in TRAPPED_SCHEMAS
    if trapped:
        parsed["trap_schedule"] = trapped_charge_runtime.plan(parsed)
        resources.update(parsed["trap_schedule"]["resources"])
    # Core ledger + optical expectations + all readout stages + explicit display arrays.
    evidence = (
        count * pixels * (256 + 192 * len(formats)) + resources["unique_spectral_samples"] * 8
    )
    if source_ri:
        evidence += sum(source_ri_map_bytes.values())
    if "charge_collection" in base:
        evidence += (
            int(np.prod(_collection_support_shape(base))) * len(parsed["unique"])
            * _collection_evidence_count(base) * 8
        )
    if "unmodulated" in parsed:
        unmodulated = parsed["unmodulated"]
        unmodulated_base = unmodulated["base"]
        collection_bytes = (
            int(np.prod(_collection_support_shape(unmodulated_base)))
            * len(unmodulated["unique"])
            * _collection_evidence_count(unmodulated_base) * 8
            if "charge_collection" in unmodulated_base else 0
        )
        evidence += (
            count * pixels * (len(base.get("channels", CHANNELS)) * 8 * 2)
            + len(unmodulated["unique"]) * pixels * len(base.get("channels", CHANNELS)) * 8
            + count * len(unmodulated["unique"]) * base["size"][0] * 8
            + collection_bytes
        )
    optical_evidence = {
        **_native_response_arrays(base),
        **_field_psf_arrays(base),
        **_radial_response_arrays(base),
    }
    evidence += sum(array.nbytes for array in optical_evidence.values()) + base["kernels"].nbytes
    if trapped:
        evidence += count * pixels * 10 * 8 + resources["trap_timing_evidence_bytes_estimate"]
    gain_merge = program["schema"] in GAIN_MERGE_SCHEMAS
    if gain_merge:
        evidence += count * pixels * 96
    if photo_hdr:
        evidence += count * pixels * 128 + pixels * 96
    resources.update(
        retained_ledger_bytes_estimate=count * pixels * 14 * 8,
        output_array_bytes_estimate=evidence,
        readouts=count * len(formats),
        readouts_per_frame=len(formats),
        state_scope=("one_immutable_full_sequence_job"
                     if base["geometry"]["crop_origin"] == [0, 0]
                     and base["geometry"]["full_sensor_shape"] == list(base["size"])
                     else "one_immutable_native_receiver_roi_sequence_job"),
    )
    resources["working_array_bytes_estimate"] += evidence * 2
    if gain_merge:
        resources["gain_merge_peak_bytes_estimate"] = pixels * (
            768 if model["schema"].endswith("_v2") else 384
        )
        resources["working_array_bytes_estimate"] += resources[
            "gain_merge_peak_bytes_estimate"
        ]
    if photo_hdr:
        resources["working_array_bytes_estimate"] += count * pixels * 192 + pixels * 128
    if trapped:
        resources["working_array_bytes_estimate"] += resources[
            "trap_segment_working_bytes_estimate"
        ]
    full_pixels = int(np.prod(base["geometry"]["full_sensor_shape"]))
    if full_pixels != pixels:
        # Seeded PRNU/DSNU are drawn in full native raster order before slicing.
        # Account for temporary full-resolution draws, clipping and scale arrays.
        resources["full_native_pattern_bytes_estimate"] = full_pixels * 48
        resources["working_array_bytes_estimate"] += full_pixels * 48
    if evidence > MAX_EVIDENCE_BYTES or resources["working_array_bytes_estimate"] > 1024**3:
        raise ValueError("Retained ledger/readout evidence exceeds bounded array budget")
    parsed["resources"] = resources
    # Known gap dark and temperature laws must fail before queuing, not only
    # after optical integration in the worker. Fixed-pattern draws are local
    # deterministic maps and do not consume either sequence noise stream.
    prnu, dark, pattern = electrical._patterns(
        model, tuple(base["geometry"]["full_sensor_shape"]),
        tuple(base["geometry"]["crop_origin"]), tuple(base["size"]), temperature
    )
    for frame, event in zip(control["frames"], schedule["frames"], strict=True):
        durations = [
            np.asarray(event["row_gap_ns"])[:, None] / 1e9,
            frame["applied"]["exposure_ns"] / 1e9,
        ]
        for duration in durations:
            with np.errstate(over="ignore", invalid="ignore"):
                mean = dark * duration
            if not np.isfinite(mean).all() or np.any(mean > electrical.MAX_CHARGE_E):
                raise ValueError(
                    "Retained gap/exposure dark generation exceeds the bounded charge domain"
                )
    parsed["generation_patterns"] = (prnu, dark, pattern)
    return parsed


