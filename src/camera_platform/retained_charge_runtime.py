def _readout_module(model):
    from . import dcg_electrical, nonlinear_dcg, nonlinear_readout

    modules = {
        "camera_electrical_readout_v1": electrical,
        "camera_electrical_readout_v2": nonlinear_readout,
        "camera_shared_charge_readout_v1": dcg_electrical,
        "camera_shared_charge_readout_v2": nonlinear_dcg,
    }
    if (
        not isinstance(model, Mapping)
        or not isinstance(model.get("schema"), str)
        or model["schema"] not in modules
    ):
        raise ValueError("Retained charge requires an explicit supported electrical readout")
    return modules[model["schema"]]


def _paired(model):
    return model["schema"].startswith("camera_shared_charge_readout_")


def _raw_formats(model):
    nonlinear = model["schema"].endswith("_v2")
    adcs = [path["adc"] for path in model["paths"]] if _paired(model) else [model["adc"]]
    return [
        {
            "cfa": "RGGB",
            "bit_depth": adc["bit_depth"],
            "black_level_dn": adc["black_level_dn"],
            "response_type": "nonlinear_charge_voltage" if nonlinear else "linear",
            "packing": "unpacked",
            "layout": "bayer",
            "hdr_streams": 1,
        }
        for adc in adcs
    ]


def _source_ri_component_evidence(component, map_array, flux_key):
    """Keep source-grid provenance separate from the receiver RAW geometry."""
    base = component["base"]
    subcell = base["source_subcells"] is not None
    source_support = base.get("source_support", {
        **base["geometry"], "shape": list(base["image"].shape[:2]),
    })
    return {
        "map_array": map_array,
        "map_unit": "1",
        "map_axes": (["source_row", "source_col", "subrow", "subcol", "wavelength"]
                     if subcell else ["source_row", "source_col", "wavelength"]),
        "source_support": deepcopy(source_support),
        "receiver_crop": deepcopy(base.get("capture_support", base["geometry"])),
        "scene_content_hashes": component["scene_hashes"].copy(),
        "flux_ledger": flux_key,
        "flux_unit": "W/nm",
        **({"source_subcell_evidence_per_scene": [
            deepcopy(item["scene"]["source_subcell_evidence"])
            for item in component["unique"]
        ]} if subcell else {}),
    }


def validate_capture_program(payload):
    schema = payload.get("schema") if isinstance(payload, Mapping) else None
    required = {
        "schema",
        "electrical_model",
        "retained_charge_model",
        "waveform",
        "event_contract",
        "pd_clear_before_exposure",
        "preview",
    }
    if schema in GAIN_MERGE_SCHEMAS:
        required.add("gain_merge_profile")
    if schema == PHOTO_HDR_PROGRAM_SCHEMA:
        required.add("photo_hdr_profile")
    if not isinstance(payload, Mapping) or set(payload) != required:
        raise ValueError("Retained capture program requires every explicit contract field")
    if schema not in (PROGRAM_SCHEMA, TRAPPED_PROGRAM_SCHEMA, PHOTO_HDR_PROGRAM_SCHEMA,
                      *GAIN_MERGE_SCHEMAS):
        raise ValueError("Unsupported retained capture program schema")
    trapped = schema in TRAPPED_SCHEMAS
    event_contract = TRAP_EVENT_CONTRACT if trapped else EVENT_CONTRACT
    module = _readout_module(payload["electrical_model"])
    validator = (
        electrical.validate_electrical_model if module is electrical else module.validate_model
    )
    model = validator(payload["electrical_model"])
    reservoir = (trapped_charge if trapped else retained_charge).validate_model(
        payload["retained_charge_model"]
    )
    capacity = model["shared_charge_capacity_e" if _paired(model) else "full_well_e"]
    if reservoir["capacity_e"] != capacity:
        raise ValueError("Integer retained capacity must equal the readout full well")
    if (
        payload["event_contract"] != event_contract
        or payload["preview"] != PREVIEW
        or type(payload["preview"].get("charge_inversion")) is not bool
    ):
        raise ValueError("Retained event and delivered-code preview contracts must be explicit")
    policies = payload["pd_clear_before_exposure"]
    if not isinstance(policies, list) or not 1 <= len(policies) <= MAX_FRAMES:
        raise ValueError("Retained PD clear policy requires one entry per ordered frame")
    ids = []
    for item in policies:
        if (
            not isinstance(item, Mapping)
            or set(item) != {"frame_id", "clear"}
            or not isinstance(item["frame_id"], str)
            or not item["frame_id"].strip()
            or len(item["frame_id"]) > 200
            or type(item["clear"]) is not bool
        ):
            raise ValueError("Each PD clear policy requires a frame ID and boolean clear")
        ids.append(item["frame_id"])
    if len(set(ids)) != len(ids):
        raise ValueError("PD clear policies require unique ordered frame IDs")
    result = {
        "schema": payload["schema"],
        "electrical_model": model,
        "retained_charge_model": reservoir,
        "waveform": None if payload["waveform"] is None else validate_waveform(payload["waveform"]),
        "event_contract": deepcopy(event_contract),
        "preview": deepcopy(PREVIEW),
        "pd_clear_before_exposure": deepcopy(policies),
    }
    if schema in GAIN_MERGE_SCHEMAS:
        result["gain_merge_profile"] = retained_gain_merge.validate_profile(
            model, payload["gain_merge_profile"]
        )
    if schema == PHOTO_HDR_PROGRAM_SCHEMA:
        if model["schema"] != electrical.SCHEMA or _paired(model):
            raise ValueError("Stateful photo HDR requires linear single-path readout")
        result["photo_hdr_profile"] = retained_hdr.validate_profile(
            payload["photo_hdr_profile"]
        )
    return result


def default_capture_program(legacy_readout, frame_ids):
    model = electrical.default_electrical_model(legacy_readout)
    capacity = model["full_well_e"]
    if int(capacity) != capacity:
        raise ValueError("Retained charge requires an integer full well")
    return validate_capture_program(
        {
            "schema": PROGRAM_SCHEMA,
            "electrical_model": model,
            "retained_charge_model": {
                "schema": "camera_retained_photodiode_v1",
                "capacity_e": int(capacity),
                "transfer_efficiency": [0.8, 0.8, 0.8, 0.8],
            },
            "waveform": None,
            "event_contract": deepcopy(EVENT_CONTRACT),
            "pd_clear_before_exposure": [
                {"frame_id": identity, "clear": False} for identity in frame_ids
            ],
            "preview": deepcopy(PREVIEW),
        }
    )


def default_trapped_capture_program(legacy_readout, frame_ids):
    """Authored numerical example; no fitted device trap parameters implied."""
    program = default_capture_program(legacy_readout, frame_ids)
    model = program["retained_charge_model"]
    program.update(schema=TRAPPED_PROGRAM_SCHEMA, event_contract=deepcopy(TRAP_EVENT_CONTRACT))
    model.update(
        schema=trapped_charge.SCHEMA,
        trap_capacity_e=[max(1, model["capacity_e"] // 10)] * 4,
        capture_rate_s=[10.] * 4,
        release_time_s=[0.01] * 4,
        integration={
            "method": trapped_charge.METHOD, "max_step_ns": 100_000,
            "max_transition_probability": trapped_charge.MAX_TRANSITION_PROBABILITY,
        },
    )
    return validate_capture_program(program)


def default_gain_merge_capture_program(legacy_readout, frame_ids, *, trapped=False):
    """Authored linear HCG/LCG example with explicit stateful RAW-only merge."""
    from . import dcg_electrical

    program = (
        default_trapped_capture_program(legacy_readout, frame_ids)
        if trapped else default_capture_program(legacy_readout, frame_ids)
    )
    model = dcg_electrical.default_model(legacy_readout)
    program["schema"] = (
        TRAPPED_GAIN_MERGE_PROGRAM_SCHEMA if trapped else GAIN_MERGE_PROGRAM_SCHEMA
    )
    program["electrical_model"] = model
    program["retained_charge_model"]["capacity_e"] = int(model["shared_charge_capacity_e"])
    program["gain_merge_profile"] = retained_gain_merge.default_profile(model)
    return validate_capture_program(program)


def default_photo_hdr_capture_program(legacy_readout, frame_ids):
    """Authored trap-free partial-transfer HDR; distinct exposures are a run gate."""
    program = default_capture_program(legacy_readout, frame_ids)
