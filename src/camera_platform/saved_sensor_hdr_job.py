"""Typed Worker lifecycle for a pinned static saved-sensor RAW HDR bracket."""

from __future__ import annotations

import hashlib
import math
import tempfile
from copy import deepcopy
from pathlib import Path
from typing import Any

from .registry import IntegrityError, canonical, digest

SCHEMA = "camerae2e_saved_sensor_hdr_study_v1"
JOB_KIND = "saved_sensor_hdr"
LIMITATION = (
    "Static independent-reset bracket from one saved sensor model. The existing "
    "scalar RAW HDR calibration cannot represent saved per-pixel PRNU/DSNU, so this "
    "study explicitly sets four FPN terms to zero while retaining saved spectral "
    "response and scalar readout. No PWM/LFM, motion, rolling shutter, measured "
    "accuracy, or native-FPN HDR claim."
)
MODEL_FPN_LIMITATION = (
    "Static independent-reset RAW bracket with the saved sensor's native FPN "
    "terms retained. HDR merge inverts pixel/column gain and signed bias using "
    "the exact maps generated by the same simulation model. This is an oracle "
    "model-known calibration, not independent dark/flat measurement. It does "
    "not establish motion, PWM/LFM, real-product timing or physical accuracy."
)


def default_spec() -> dict[str, Any]:
    return {
        "schema": SCHEMA,
        "name": "저장 센서 RAW HDR 노출 브래킷",
        "sensor_revision": {"identifier": "", "run_id": ""},
        "exposure_s": [0.001, 0.016],
        "luminance_cd_m2": 1000.0,
        "output_size": [32, 32],
        "seed": 7,
        "fixed_pattern_mode": "zero_fpn_override",
        "acknowledge_simulation_limits": False,
    }


def specification(payload: dict[str, Any]) -> dict[str, Any]:
    from .saved_sensor_hdr import FPN_NATIVE, FPN_OVERRIDE, _exposures, _number

    if not isinstance(payload, dict) or set(payload) != set(default_spec()):
        raise ValueError("Declare exactly the saved sensor HDR study fields.")
    if payload["schema"] != SCHEMA or payload["acknowledge_simulation_limits"] is not True:
        raise ValueError("Explicit saved HDR simulation-limit acknowledgement required.")
    if payload["fixed_pattern_mode"] not in {FPN_OVERRIDE, FPN_NATIVE}:
        raise ValueError("Saved HDR requires zero_fpn_override or model_known_native_fpn.")
    name = payload["name"]
    if not isinstance(name, str) or not 1 <= len(name.strip()) <= 160:
        raise ValueError("Study name requires 1..160 characters.")
    revision = payload["sensor_revision"]
    if (
        not isinstance(revision, dict)
        or set(revision) != {"identifier", "run_id"}
        or any(not isinstance(revision[key], str) or not 1 <= len(revision[key].strip()) <= 128
               for key in ("identifier", "run_id"))
    ):
        raise ValueError("Select one explicit saved sensor run and identifier.")
    exposures = _exposures(payload["exposure_s"])
    luminance = _number(payload["luminance_cd_m2"], "luminance_cd_m2", 0.01, 10000.0)
    if payload["output_size"] != [32, 32]:
        raise ValueError("Saved HDR strip chart requires 32x32 output_size.")
    if type(payload["seed"]) is not int or not 0 <= payload["seed"] < 2**32:
        raise ValueError("seed must be a uint32 integer.")
    selected = deepcopy(payload)
    selected["name"] = name.strip()
    selected["exposure_s"] = exposures
    selected["luminance_cd_m2"] = luminance
    return selected


def _db_root(service: Any) -> Path:
    return Path(service.workspace) / "camerae2e_db"


def prepare(service: Any, payload: dict[str, Any]) -> dict[str, Any]:
    from pyisetcam.sensor_simulation_db import (
        sensor_simulation_db_config,
        sensor_simulation_db_get,
    )

    from .imaging import _current
    from .offline_assets import offline_asset_identity
    from .sensor_db_bridge import inspect_sensor_revision

    spec = specification(payload)
    selected = spec["sensor_revision"]
    source = inspect_sensor_revision(
        selected["identifier"], root=_db_root(service), run_id=selected["run_id"]
    )
    if not source["executable"]:
        raise ValueError(f"Saved sensor run cannot execute: {source['reason']}")
    revision = source["revision"]
    if revision["model"] not in {"db_estimate_v1", "physical_estimate_v1"}:
        raise ValueError("Saved HDR requires pinned DB/physical estimate snapshots.")
    saved = sensor_simulation_db_get(
        revision["report_code"], root=_db_root(service), run_id=revision["run_id"]
    )
    settings = saved["metadata"].get("simulation_settings") or {}
    if settings.get("fnumber") != 4.0 or settings.get("focal_length_m") != 0.004:
        raise ValueError("Saved HDR requires saved F/4, 4 mm optics.")
    scenario = sensor_simulation_db_config(
        revision["report_code"], root=_db_root(service), run_id=revision["run_id"]
    )["scenario"]
    if scenario.get("sensor_output_mode") != "digital_raw":
        raise ValueError("Saved HDR requires digital_raw output.")
    cfa = saved["metadata"].get("native_cfa") or {}
    if cfa.get("pattern") != [[1, 2], [3, 4]] or cfa.get("filter_names") != [
        "R", "Gr", "Gb", "B"
    ]:
        raise ValueError("Saved HDR currently requires native R/Gr/Gb/B Bayer CFA.")
    fpn = (saved["metadata"].get("readout_profile") or {}).get("fixed_pattern") or {}
    if set(fpn) != {
        "prnu_fraction", "dsnu_e", "column_prnu_fraction", "column_dsnu_e"
    } or any(type(value) not in (int, float) or not math.isfinite(float(value))
             for value in fpn.values()):
        raise ValueError("Saved HDR requires explicit finite FPN provenance.")
    return {
        "name": spec["name"],
        "job_kind": JOB_KIND,
        "plugin_id": SCHEMA,
        "specification": spec,
        "source_identity": source["revision"],
        "upstream_assets": offline_asset_identity(workspace=service.workspace),
        "environment": _current(service),
        "limitation": (
            MODEL_FPN_LIMITATION
            if spec["fixed_pattern_mode"] == "model_known_native_fpn"
            else LIMITATION
        ),
    }


def submit(service: Any, payload: dict[str, Any]) -> dict[str, Any]:
    frozen = prepare(service, payload)
    return service.registry.submit(frozen, digest(frozen))


def execute(service: Any, job: dict[str, Any]) -> dict[str, Any]:
    from .saved_sensor_hdr import evaluate_saved_sensor_hdr_bracket

    if service.registry.get_run(job["id"])["status"] != "running":
        raise RuntimeError("Saved sensor HDR study is not running or was cancelled.")
    fresh = prepare(service, job["specification"])
    if any(canonical(job.get(key)) != canonical(value) for key, value in fresh.items()):
        raise IntegrityError("Frozen saved HDR source, assets or request changed.")
    spec = fresh["specification"]
    selected = spec["sensor_revision"]
    with tempfile.TemporaryDirectory(prefix="camera-saved-hdr-") as temporary:
        report = evaluate_saved_sensor_hdr_bracket(
            selected["identifier"],
            run_id=selected["run_id"],
            root=_db_root(service),
            workspace=service.workspace,
            output_dir=Path(temporary) / "evidence",
            exposure_s=spec["exposure_s"],
            luminance_cd_m2=spec["luminance_cd_m2"],
            output_size=spec["output_size"],
            seed=spec["seed"],
            fixed_pattern_mode=spec["fixed_pattern_mode"],
        )
        if any(report["revision"][key] != fresh["source_identity"][key]
               for key in ("run_id", "result_sha256", "config_sha256")):
            raise IntegrityError("Saved HDR report differs from its frozen source.")
        if report["upstream_assets"] != fresh["upstream_assets"]:
            raise IntegrityError("Saved HDR upstream assets changed.")
        artifacts = []
        saved_artifacts = {}
        for kind, media in (("json", "application/json"), ("npz", "application/octet-stream")):
            content = Path(report["artifacts"][kind]).read_bytes()
            if hashlib.sha256(content).hexdigest() != report["artifact_sha256"][kind]:
                raise IntegrityError("Saved HDR artifact hash differs from its result.")
            descriptor = service.registry.store_blob(
                content, f"saved-sensor-hdr-evidence.{kind}", media
            )
            artifacts.append(descriptor)
            saved_artifacts[kind] = descriptor
        report = {key: value for key, value in report.items()
                  if key not in {"artifacts", "artifact_sha256"}}
        report["artifacts"] = saved_artifacts
        if canonical(prepare(service, spec)) != canonical(fresh):
            raise IntegrityError("Saved HDR source, assets or executable changed during study.")
        if service.registry.get_run(job["id"])["status"] != "running":
            raise RuntimeError("Saved HDR study was cancelled during execution.")
    summary = {
        "schema": SCHEMA,
        "status": "completed",
        "specification": spec,
        "source_identity": fresh["source_identity"],
        "upstream_assets": fresh["upstream_assets"],
        "report": report,
        "verification": report["verification"],
        "limitation": fresh["limitation"],
    }
    artifacts.append(service.registry.store_blob(
        canonical(summary).encode(), "saved-sensor-hdr-result.json", "application/json"
    ))
    return {"summary": summary, "artifacts": artifacts}


def get(service: Any, identity: str) -> dict[str, Any]:
    job = service.registry.get_run(identity)
    if job.get("job_kind") != JOB_KIND:
        raise ValueError("Selected job is not a saved sensor HDR study.")
    summary = (job.get("result") or {}).get("summary")
    if summary is not None:
        for key in ("specification", "source_identity", "upstream_assets"):
            if canonical(summary[key]) != canonical(job[key]):
                raise IntegrityError("Saved HDR result differs from its frozen request.")
        if job["status"] == "succeeded":
            for descriptor in summary["report"]["artifacts"].values():
                if descriptor not in job["artifacts"]:
                    raise IntegrityError("Saved HDR evidence link is missing.")
            for descriptor in job["artifacts"]:
                content = service.registry.blob_path(descriptor["sha256"]).read_bytes()
                if hashlib.sha256(content).hexdigest() != descriptor["sha256"]:
                    raise IntegrityError("Saved HDR artifact bytes differ.")
            result = [item for item in job["artifacts"]
                      if item["name"] == "saved-sensor-hdr-result.json"]
            if len(result) != 1 or service.registry.blob_path(
                result[0]["sha256"]
            ).read_bytes() != canonical(summary).encode():
                raise IntegrityError("Saved HDR result differs from its artifact.")
    return job


def list_records(service: Any) -> list[dict[str, Any]]:
    return [
        {key: item.get(key) for key in ("id", "name", "status", "created_at", "error")}
        for item in service.registry.list_runs() if item.get("job_kind") == JOB_KIND
    ]


def install_routes(app: Any, service: Any) -> None:
    from fastapi.responses import Response

    @app.get("/api/v1/saved-sensor-hdr/template", tags=["saved_sensor_hdr"])
    def template(q: str = ""):
        from .sensor_db_bridge import sensor_revision_catalog

        return {
            "specification": default_spec(),
            "sensor_catalog": sensor_revision_catalog(root=_db_root(service), query=q or None),
            "fixed_pattern_modes": ["zero_fpn_override", "model_known_native_fpn"],
            "limitation": LIMITATION,
            "model_known_fpn_limitation": MODEL_FPN_LIMITATION,
        }

    @app.post("/api/v1/saved-sensor-hdr", status_code=202, tags=["saved_sensor_hdr"])
    def create(payload: dict):
        return submit(service, payload)

    @app.get("/api/v1/saved-sensor-hdr", tags=["saved_sensor_hdr"])
    def listing():
        return list_records(service)

    @app.get("/api/v1/saved-sensor-hdr/{identity}", tags=["saved_sensor_hdr"])
    def detail(identity: str):
        return get(service, identity)

    @app.post("/api/v1/saved-sensor-hdr/{identity}/cancel", tags=["saved_sensor_hdr"])
    def cancel(identity: str):
        get(service, identity)
        return service.registry.cancel(identity)

    @app.get("/api/v1/saved-sensor-hdr/{identity}/export", tags=["saved_sensor_hdr"])
    def export(identity: str):
        return Response(
            canonical(get(service, identity)),
            media_type="application/json",
            headers={"Content-Disposition": 'attachment; filename="saved-sensor-hdr.json"'},
        )
