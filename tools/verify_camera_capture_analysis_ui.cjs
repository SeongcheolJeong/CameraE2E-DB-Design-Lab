'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {chromium}=require('playwright');
const input=JSON.parse(fs.readFileSync(process.argv[2],'utf8')),out=path.resolve(process.argv[3]);
fs.mkdirSync(out,{recursive:true});
const base=input.base_url,ids=input.records;
const report={schema:'camera_capture_analysis_ui_v1',base_url:base,state_dir:input.state_dir,checks:[],errors:[],posts:[],user_browser_profile_accessed:false};
const check=(name,value)=>{assert(value,name);report.checks.push({name,status:'passed'});};
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CAMERA_UI_BROWSER||chromium.executablePath()});
 const page=await browser.newPage({viewport:{width:1440,height:1080}});
 const get=async p=>{const r=await page.request.get(base+'/api/v1/'+p);assert(r.ok(),p);return r.json();};
 page.on('pageerror',e=>report.errors.push(String(e)));
 page.on('request',r=>{if(r.method()==='POST')report.posts.push(new URL(r.url()).pathname);});
 try{
  const before=await get('bootstrap');
  check('Explicit isolated QA state',before.state_dir===input.state_dir&&!input.state_dir.endsWith('/camera-platform'));
  const original=await get('captures/'+ids.capture);
  await page.goto(base+'/#validation');
  const panel=page.locator('[data-capture-analysis-panel]');await panel.waitFor();
  await page.locator('#analysis-capture').selectOption(ids.capture);
  check('Original provenance and shared sample meaning are visible',(await panel.innerText()).includes('독립된 실측 표본이 아닙니다')&&(await panel.innerText()).includes('simulated')&&(await panel.innerText()).includes('취득 1건'));
  check('Legacy observation remains selectable',await panel.locator('[data-analysis-legacy]').count()===1);
  check('Read-only inspection submits nothing',report.posts.length===0);
  await panel.locator('[data-analysis-authoring] summary').click();
  await page.locator('#analysis-testName').fill('Browser QA · peak response');
  await page.locator('#analysis-testRevision').fill('ui-1');
  await page.locator('#analysis-observable').selectOption('green_mean_normalized');
  await page.locator('#analysis-reduction').selectOption('peak_absolute_target_error');
  await page.locator('#analysis-target').fill('0.18');
  check('Frame window uses planned acquisition frame IDs',await page.locator('#analysis-start option').count()===33);
  const testResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/v1/tests'&&r.request().method()==='POST');
  await panel.locator('[data-analysis-form="test"] button[type="submit"]').click();
  const testReply=await testResponse;check('Common observation Test is created',testReply.ok());const test=await testReply.json();
  await page.waitForFunction(id=>document.querySelector('#analysis-test')?.value===id,test.id);
  check('New Test retains acquisition program and chosen reduction',test.stimulus.control_program_id===ids.program&&test.observation_specification.reduction==='peak_absolute_target_error');
  check('Unknown metric uncertainty remains explicit',JSON.parse(await page.locator('#analysis-uncertainty').inputValue()).kind==='unknown');
  await page.locator('#analysis-name').fill('Browser QA · original RAW peak analysis');
  await page.locator('#analysis-revision').fill('ui-1');
  await page.locator('#analysis-parent').selectOption(ids.analyses[0]);
  const analysisResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/v1/capture_analyses'&&r.request().method()==='POST');
  await panel.locator('[data-analysis-form="observe"] button[type="submit"]').click();
  const analysisReply=await analysisResponse;check('Browser reanalysis submits successfully',analysisReply.ok());const result=await analysisReply.json();
  await page.locator('[data-analysis-select="'+result.analysis.id+'"]').waitFor();
  check('Reanalysis retains exact original capture hash',result.capture.content_hash===original.content_hash);
  check('Analysis parent and dataset identity remain bound',result.analysis.parent_analysis_id===ids.analyses[0]&&JSON.stringify(result.measurement.dataset_ids)===JSON.stringify(original.dataset_ids));
  check('Incomplete window cannot invent a peak measurement',result.measurement.values.length===0&&result.analysis.observation.points[0].value===null);
  await page.locator('[data-analysis-select="'+result.analysis.id+'"]').click();
  check('Selected analysis binds exact Test and Measurement',await page.locator('#validation-test').inputValue()===test.id&&await page.locator('#validation-measurement').inputValue()===result.measurement.id);
  await page.locator('#toast').waitFor({state:'hidden',timeout:15000});
  await panel.screenshot({path:path.join(out,'analysis-panel.png')});
  await page.setViewportSize({width:390,height:844});
  check('Mobile page has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await panel.evaluate(el=>el.scrollIntoView({block:'start'}));await page.screenshot({path:path.join(out,'mobile.png')});
  await page.setViewportSize({width:1440,height:1080});
  const runResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/v1/runs'&&r.request().method()==='POST');
  await page.locator('[data-action="run-capture"][data-id="'+ids.capture+'"]').click();
  const runReply=await runResponse;check('Selected analysis camera rerun submits',runReply.ok());const queued=await runReply.json();let run;
  const deadline=Date.now()+30000;
  while(Date.now()<deadline){run=await get('runs/'+queued.id);if(['succeeded','failed','cancelled'].includes(run.status))break;await new Promise(r=>setTimeout(r,100));}
  check('Rerun uses selected analysis Test rather than another metric',run.status==='succeeded'&&run.test_id===test.id&&run.result.prediction.metric_id===test.metric_id);
  await page.locator('[data-control-result="'+queued.id+'"]').waitFor();
  await page.goto(base+'/#validation');
  await page.locator('[data-analysis-select="'+result.analysis.id+'"]').click();
  await page.locator('#validation-run').selectOption(run.id);
  const comparisonResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/v1/validations'&&r.request().method()==='POST');
  await page.locator('form[data-form="validation"] button[type="submit"]').click();
  const comparisonReply=await comparisonResponse;check('Browser comparison submits',comparisonReply.ok());const comparison=await comparisonReply.json();
  check('Missing RAW and unknown uncertainty preserve inconclusive status',comparison.status==='INCONCLUSIVE'&&!comparison.physical_validation_pass);
  await page.locator('[data-response-observation]').waitFor();
  await page.locator('#toast').waitFor({state:'hidden',timeout:15000});
  await page.locator('[data-response-observation]').screenshot({path:path.join(out,'comparison.png')});
  const after=await get('bootstrap');
  check('One new analysis adds no acquisition or dataset identity',after.counts.captures===before.counts.captures&&after.counts.capture_analyses===before.counts.capture_analyses+1&&after.counts.measurements===before.counts.measurements+1);
  check('Original acquisition record is byte-equivalent after UI workflow',JSON.stringify(await get('captures/'+ids.capture))===JSON.stringify(original));
  check('No JavaScript errors',report.errors.length===0);
  report.records={capture:ids.capture,test:test.id,analysis:result.analysis.id,measurement:result.measurement.id,run:run.id,validation:comparison.id};
  report.status='passed';
 }catch(error){report.status='failed';report.error=String(error);await page.screenshot({path:path.join(out,'debug.png')});throw error;}
 finally{fs.writeFileSync(path.join(out,'verification.json'),JSON.stringify(report,null,2)+'\n');await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
